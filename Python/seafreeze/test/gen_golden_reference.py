"""Generate ``golden_reference.json`` for the regression suite.

Run from the Python/ directory:

    python -m seafreeze.test.gen_golden_reference

The file records, for every material in ``golden_cases.GOLDEN_AXES``, the
all-properties output of ``getProp`` for one scatter case and one grid case.
NaN is stored as JSON ``null``.  The accompanying ``test_golden_regression.py``
compares the current code against this file.

Regenerate only when a numerical change is intended (new spline file, fixed
formula) and commit the JSON with that change so the diff documents it.
"""

import json
import os
import warnings

import numpy as np

import seafreeze as sf
from seafreeze.test.golden_cases import GOLDEN_AXES

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_PATH = os.path.join(HERE, 'golden_reference.json')


def build_scatter(axes):
    n = len(axes['P'])
    PTm = np.empty(n, dtype=object)
    for i in range(n):
        if axes['m'] is None:
            PTm[i] = (axes['P'][i], axes['T'][i])
        else:
            PTm[i] = (axes['P'][i], axes['T'][i], axes['m'][i])
    return PTm


def build_grid(axes):
    k = 2 if axes['m'] is None else 3
    PTm = np.empty(k, dtype=object)
    PTm[0] = np.array(axes['P'], dtype=float)
    PTm[1] = np.array(axes['T'], dtype=float)
    if k == 3:
        PTm[2] = np.array(axes['m'], dtype=float)
    return PTm


def _to_jsonable(arr):
    a = np.asarray(arr, dtype=float)
    return np.where(np.isfinite(a), a, None).tolist() if a.ndim else (float(a) if np.isfinite(a) else None)


def evaluate(material, axes):
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        sc = sf.getProp(build_scatter(axes), material)
        gr = sf.getProp(build_grid(axes), material)
    return {
        'scatter': {k: _to_jsonable(v) for k, v in vars(sc).items()},
        'grid':    {k: _to_jsonable(v) for k, v in vars(gr).items()},
    }


def main():
    ref = {
        '_meta': {
            'note': 'Generated by seafreeze/test/gen_golden_reference.py. '
                    'Do not edit by hand; regenerate and commit with the change.',
            'numpy': np.__version__,
        },
        'cases': {mat: evaluate(mat, axes) for mat, axes in GOLDEN_AXES.items()},
    }
    with open(OUT_PATH, 'w') as fh:
        json.dump(ref, fh, indent=1, sort_keys=True)
    nprops = sum(len(c['scatter']) + len(c['grid']) for c in ref['cases'].values())
    print(f'Wrote {OUT_PATH}: {len(ref["cases"])} materials, {nprops} property arrays.')


if __name__ == '__main__':
    main()
